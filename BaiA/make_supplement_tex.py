"""Chuyển BaiA/Supplement_BaiA.md thành LaTeX (BaiA/overleaf_supp/supplement.tex) để biên dịch trên Overleaf
thành Supplemental_Materials.pdf (ASCE không còn lưu trữ phụ lục từ 5/1/2026; file PDF đặt trong kho có DOI).

Chạy:  python BaiA/make_supplement_tex.py      (sau make_supplement.py)
Ghi:   BaiA/overleaf_supp/supplement.tex, figures/, BaiA/overleaf_supplement.zip
"""
import re
import shutil
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "Supplement_BaiA.md"
OUT = HERE / "overleaf_supp"; (OUT / "figures").mkdir(parents=True, exist_ok=True)
sys.stdout.reconfigure(encoding="utf-8")

UNI = {"‑": "-", "–": "--", "—": "---", "θ": r"$\theta$", "→": r"$\to$", "≤": r"$\le$", "≥": r"$\ge$", "×": r"$\times$",
       "²": r"$^{2}$", "³": r"$^{3}$", "°": r"$^\circ$", "σ": r"$\sigma$", "−": r"$-$", "₄": r"$_4$", "₂": r"$_2$",
       "±": r"$\pm$", "½": r"$\frac{1}{2}$", "≈": r"$\approx$", "·": r"$\cdot$", "ρ": r"$\rho$", "’": "'", "‘": "`",
       "“": "``", "”": "''", "…": r"\ldots{}", "µ": r"$\mu$"}


def esc(s):
    """Thoát ký tự đặc biệt LaTeX, rồi chuyển định dạng Markdown nội dòng."""
    keep = {}

    def hold(x):
        k = f"\x00{len(keep)}\x00"; keep[k] = x; return k
    s = re.sub(r"`([^`]+)`", lambda m: hold(r"\texttt{" + m.group(1).replace("\\", r"\textbackslash{}").replace("_", r"\_") + "}"), s)
    s = re.sub(r"(\w)\^([0-9.]+)", lambda m: m.group(1) + hold(r"$^{" + m.group(2) + "}$"), s)
    s = re.sub(r"https?://\S+?(?=[.,;]?(?:[)\s]|$))", lambda m: hold(r"\url{" + m.group(0) + "}"), s)
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")]:
        s = s.replace(a, b)
    s = s.replace(r"\textbackslash\{\}", r"\textbackslash{}")
    for a, b in UNI.items():
        s = s.replace(a, b)
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
    s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\\emph{\1}", s)
    for k, v in keep.items():
        s = s.replace(k, v)
    return s


def table(lines):
    rows = [[c.strip() for c in l.strip().strip("|").split("|")] for l in lines]
    head, body = rows[0], [r for r in rows[2:]]
    n = len(head)
    align = "l" + "r" * (n - 1)
    out = [r"\begin{center}", r"\begin{adjustbox}{max width=\textwidth, max totalheight=0.9\textheight}",
           r"\begin{tabular}{" + align + "}", r"\toprule",
           " & ".join(esc(h.replace("_", " ")) for h in head) + r" \\", r"\midrule"]
    for r in body:
        r = (r + [""] * n)[:n]
        out.append(" & ".join(esc(c) for c in r) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", r"\end{center}", ""]
    return out


md = SRC.read_text(encoding="utf-8").splitlines()
tex, i = [], 0
title = "Correcting HEC-18 Pier Scour with Field Data: Bridge-Level Validation and Conformal Bounds"
while i < len(md):
    l = md[i]
    if l.startswith("# ") or l.startswith("*Generated by") or l.strip() == "---" or l.startswith("**Correcting HEC"):
        i += 1; continue
    if l.startswith("## "):
        tex.append(r"\section*{" + esc(l[3:]) + "}"); tex.append(r"\addcontentsline{toc}{section}{" + esc(l[3:]) + "}"); i += 1; continue
    if l.startswith("### "):
        tex.append(r"\subsection*{" + esc(l[4:]) + "}"); i += 1; continue
    if l.startswith("|"):
        blk = []
        while i < len(md) and md[i].startswith("|"):
            blk.append(md[i]); i += 1
        tex += table(blk); continue
    m = re.match(r"!\[[^\]]*\]\(([^)]+)\)", l)
    if m:
        src = HERE / m.group(1); dst = OUT / "figures" / "FigS1_ngoithia.png"
        shutil.copy(src, dst)
        tex += [r"\begin{center}", r"\includegraphics[width=\textwidth]{figures/FigS1_ngoithia.png}", r"\end{center}"]; i += 1; continue
    if l.startswith("**Table S") or l.startswith("**Fig. S"):
        tex.append(r"\noindent " + esc(l)); tex.append(r"\nopagebreak"); i += 1; continue
    tex.append(esc(l)); i += 1

doc = r"""\documentclass[12pt,letterpaper]{article}
\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage{newtxtext,newtxmath}
\usepackage[margin=1in]{geometry}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{adjustbox}
\usepackage{xurl}
\usepackage[colorlinks=true,linkcolor=black,urlcolor=black]{hyperref}
\urlstyle{same}
\usepackage{setspace}
\setlength{\parindent}{0pt}
\setlength{\parskip}{6pt}
\renewcommand{\arraystretch}{1.1}
\begin{document}
\begin{center}
{\Large\bfseries Supplemental Materials}\\[6pt]
{\large """ + title + r"""}\\[10pt]
Quang Huy Mai, Dang Phong Nguyen, Thi Thao Pham, and Lan Huong Ho\\
Faculty of Civil and Environmental Engineering, University of Transport and Communications, Hanoi, Vietnam\\[4pt]
Corresponding author: Quang Huy Mai (\url{mqhuy@utc.edu.vn})
\end{center}

All numbers in these materials are generated by the scripts of the study repository (\texttt{BaiA/make\_supplement.py} and the analysis scripts it reads from). Sections S1--S8, Tables S1--S24 and Fig.~S1 are cited in the main paper.

\tableofcontents
\clearpage
""" + "\n".join(tex) + "\n\\end{document}\n"
doc = re.sub(r"\n{3,}", "\n\n", doc)
(OUT / "supplement.tex").write_text(doc, encoding="utf-8")
bad = sorted(set(c for c in doc if ord(c) > 126)); print("non-ASCII left:", bad)
print("braces:", doc.count("{") - doc.count("}"))
z = HERE / "overleaf_supplement.zip"
with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as f:
    f.write(OUT / "supplement.tex", "supplement.tex"); f.write(OUT / "figures" / "FigS1_ngoithia.png", "figures/FigS1_ngoithia.png")
print("wrote", OUT / "supplement.tex", "and", z)
